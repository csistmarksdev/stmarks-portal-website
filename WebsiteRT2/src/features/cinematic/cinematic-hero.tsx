"use client";

import { useEffect, useRef, type ReactNode } from "react";

import { useHeroScroll } from "@/providers/hero-scroll-provider";

import {
  useFrameSequence,
  type DrawFrame,
  type FrameSet,
} from "./use-frame-sequence";

const frameCount = 300;
const frameName = (index: number) =>
  `ezgif-frame-${index.toString().padStart(3, "0")}.jpg`;

/**
 * The single frame shown as a still in Simple mode and under
 * `prefers-reduced-motion`: the opening frame, so the still site opens on the
 * same picture the animated one does.
 */
const STILL_FRAME = 1;

/**
 * Retina is worth it; 3x on a phone is four times the fill rate of 2x for no
 * perceptible gain on a photographic frame, and it is paid on every repaint.
 */
const DESKTOP: FrameSet = {
  src: (i) => `/frames/${frameName(i)}`,
  maxDpr: 2,
  // 1920x1080 frames, ~8MB decoded each.
  decodeAhead: 10,
};

/**
 * Portrait screens: the centre 3:4 of each frame at 675x900, generated by
 * `scripts/generate-mobile-frames.mjs`. `cover` on a portrait screen only ever
 * showed that middle strip, so a phone now decodes a third of the pixels for
 * the same picture. 1.5x is already past what a 900px-tall source can fill.
 */
const MOBILE: FrameSet = {
  src: (i) => `/frames-m/${frameName(i)}`,
  maxDpr: 1.5,
  // 675x900, ~2.4MB decoded each: a phone can afford to see further ahead.
  decodeAhead: 18,
};

const MOBILE_QUERY = "(max-aspect-ratio: 3/4)";

/** Draws `source` cropped to cover the canvas box, centred. */
const drawImageCover: DrawFrame = (ctx, img, canvasWidth, canvasHeight) => {
  const ratio = Math.max(canvasWidth / img.width, canvasHeight / img.height);
  const newWidth = img.width * ratio;
  const newHeight = img.height * ratio;

  ctx.drawImage(
    img,
    (canvasWidth - newWidth) / 2,
    (canvasHeight - newHeight) / 2,
    newWidth,
    newHeight,
  );

  scheduleEdgeSample(img, canvasWidth / ratio, canvasHeight / ratio);
};

/*
 * The browser bars, kept in step with the photograph.
 *
 * iOS Safari 26+ draws the photograph itself behind its bars (see
 * `html[data-ios-glass]` in globals.css). Older Safari, and Safari 26 wherever
 * something fixed still claims an edge, paints its bars a flat colour taken
 * from the page background instead - so while over the hero that background
 * is the photograph's own top edge, `--hero-edge-top`, with the foot in
 * `--hero-edge-bottom` for the sticky stage's background.
 *
 * Measured once the scroll comes to rest, never during it: a colour that
 * changes mid-scroll is a full repaint of the page background on every
 * change, and the bars only need to agree with the frame the reader stops on.
 * And measured off the source image, on an 8x8 scratch canvas - never by
 * reading back the hero canvas, which on iOS stalls the GPU and can push the
 * canvas off acceleration altogether.
 *
 * Darkened by exactly what lies over each edge on screen: the stage's scrim
 * (`hero-stage.tsx`: black 30% at the top, 80% at the foot) and, at the top,
 * the header's legibility gradient (black 45%).
 */
const TOP_LIGHT = (1 - 0.3) * (1 - 0.45);
const BOTTOM_LIGHT = 1 - 0.8;
const SAMPLE_AFTER_MS = 180;
const SAMPLE_SIZE = 8;

let sampleTimer: number | undefined;
let sampleCanvas: HTMLCanvasElement | undefined;

function scheduleEdgeSample(
  img: CanvasImageSource & { width: number; height: number },
  visibleWidth: number,
  visibleHeight: number,
): void {
  if (typeof window === "undefined") return;
  window.clearTimeout(sampleTimer);
  sampleTimer = window.setTimeout(
    () => sampleEdges(img, visibleWidth, visibleHeight),
    SAMPLE_AFTER_MS,
  );
}

function sampleEdges(
  img: CanvasImageSource & { width: number; height: number },
  visibleWidth: number,
  visibleHeight: number,
): void {
  sampleCanvas ??= document.createElement("canvas");
  sampleCanvas.width = SAMPLE_SIZE;
  sampleCanvas.height = SAMPLE_SIZE;
  const ctx = sampleCanvas.getContext("2d", { willReadFrequently: true });
  if (!ctx) return;
  try {
    // The part of the frame actually on screen (cover crop), squeezed to 8x8.
    ctx.drawImage(
      img,
      (img.width - visibleWidth) / 2,
      (img.height - visibleHeight) / 2,
      visibleWidth,
      visibleHeight,
      0,
      0,
      SAMPLE_SIZE,
      SAMPLE_SIZE,
    );
    const top = rowColour(ctx, 0, TOP_LIGHT);
    const bottom = rowColour(ctx, SAMPLE_SIZE - 1, BOTTOM_LIGHT);
    const root = document.documentElement.style;
    if (top) root.setProperty("--hero-edge-top", top);
    if (bottom) root.setProperty("--hero-edge-bottom", bottom);
  } catch {
    // A tainted or unavailable image: keep the colours already set.
  }
}

function rowColour(
  ctx: CanvasRenderingContext2D,
  y: number,
  light: number,
): string | null {
  const { data } = ctx.getImageData(0, y, SAMPLE_SIZE, 1);
  let r = 0;
  let g = 0;
  let b = 0;
  let n = 0;
  for (let i = 0; i < data.length; i += 4) {
    if (data[i + 3] < 8) continue;
    r += data[i];
    g += data[i + 1];
    b += data[i + 2];
    n++;
  }
  if (!n) return null;
  const c = (v: number) => Math.round((v / n) * light);
  return `rgb(${c(r)} ${c(g)} ${c(b)})`;
}

export interface CinematicHeroProps {
  /** Overlay content rendered above the canvas (title, scroll cue). */
  children?: ReactNode;
  /**
   * Section height as a multiple of the viewport. The animation is spread
   * across this distance - 5 means 500vh, matching the original component.
   */
  scrollLength?: number;
}

/**
 * Scroll-driven image sequence.
 *
 * The drawing logic is unchanged from the original component. Two things were
 * adapted so it can live above the rest of the page rather than being the
 * whole page:
 *
 * 1. Progress is measured against *this section's* scroll range instead of
 *    `document.documentElement.scrollTop / scrollHeight`. With page content
 *    below the hero, document-based progress would stretch the animation
 *    across the entire page and frames would still be advancing while the
 *    reader was at the footer.
 * 2. The canvas appears once the first handful of frames have decoded rather
 *    than waiting for all 300 (~16 MB), so the hero paints quickly. Remaining
 *    frames continue loading in the background and each `onload` redraws if
 *    it is the frame currently in view.
 *
 * Loading, decoding and drawing live in `useFrameSequence`, which serves
 * portrait phones a cropped, smaller set and decodes frames ahead of the
 * scroll so no frame change waits on a JPEG decode.
 */
export function CinematicHero({
  children,
  scrollLength = 5,
}: CinematicHeroProps) {
  const containerRef = useRef<HTMLDivElement>(null);
  const stickyRef = useRef<HTMLDivElement>(null);

  const { progress, registerHero } = useHeroScroll();

  const { canvasRef, isReady, reducedMotion, setFrame } = useFrameSequence({
    frameCount,
    desktop: DESKTOP,
    mobile: MOBILE,
    mobileQuery: MOBILE_QUERY,
    draw: drawImageCover,
    stillFrame: STILL_FRAME,
  });

  // Tell the header a cinematic hero owns the top of this page.
  useEffect(() => registerHero(), [registerHero]);

  /*
   * One scroll listener, one rAF, one layout read per frame.
   *
   * Progress and the frame index are the same measurement, so they are taken
   * together. Splitting them across two listeners meant two `scroll` handlers,
   * two rAF callbacks and - because `getBoundingClientRect` inside rAF forces
   * layout - two synchronous reflows on every frame of a scroll that also has
   * Lenis, five overlay scenes and a canvas repaint on it. That was the second
   * half of the stutter.
   */
  useEffect(() => {
    const container = containerRef.current;
    if (!container) return;

    let ticking = false;

    const measure = () => {
      ticking = false;

      // Progress through this section only: 0 when its top reaches the
      // viewport top, 1 when its bottom does. Measured against the pinned
      // panel, not `window.innerHeight`: the two disagree by the height of the
      // mobile address bar, which would put progress slightly out of step with
      // what is actually on screen.
      const { top, height } = container.getBoundingClientRect();
      const pinned = stickyRef.current?.offsetHeight ?? window.innerHeight;
      const scrollable = height - pinned;
      /*
       * With nothing to scroll through - Simple mode collapses the sequence to
       * one still screen - progress is simply whether the reader has left it.
       * Pinning it at 0 told the header the opening never ended, so it kept
       * its over-the-hero look for the whole page.
       */
      const fraction =
        scrollable > 0
          ? Math.min(Math.max(-top / scrollable, 0), 1)
          : top < 0
            ? 1
            : 0;

      progress.set(fraction);

      // Progress still drives the overlay scenes and the header, which handle
      // reduced motion themselves; only the frame scrubbing stops.
      if (reducedMotion) return;

      setFrame(Math.min(frameCount - 1, Math.floor(fraction * frameCount)));
    };

    const onScroll = () => {
      if (ticking) return;
      ticking = true;
      requestAnimationFrame(measure);
    };

    measure();
    window.addEventListener("scroll", onScroll, { passive: true });
    window.addEventListener("resize", onScroll);

    return () => {
      window.removeEventListener("scroll", onScroll);
      window.removeEventListener("resize", onScroll);
    };
  }, [progress, reducedMotion, setFrame]);

  return (
    <div
      ref={containerRef}
      /*
       * `svh`, not `dvh`, and deliberately a different unit from the pinned
       * panel below.
       *
       * The panel must track the *visible* viewport, so it stays `dvh`. This
       * container must not: at `scrollLength` 8, a `dvh` height multiplies
       * every address-bar collapse by eight, so one flick on a phone changed
       * the document height by ~480px and shunted every section below the hero
       * up or down by that much mid-scroll - read as the page snapping to the
       * neighbouring section. `svh` is fixed for the life of the viewport, so
       * the document height is stable.
       *
       * Mixing units is safe here because nothing assumes they agree: the
       * scroll handler measures the real container box and the real panel
       * height every frame and derives progress from those, so the frames stay
       * in step whatever the address bar does.
       */
      style={{ height: `${scrollLength * 100}svh` }}
      // Collapsed to one still screen in Simple mode - see globals.css.
      data-frame-sequence
      // Pinned without `sticky` on iOS Safari 26+ - see globals.css.
      data-hero-pin
      className="relative bg-[var(--hero-edge-bottom)]"
    >
      {/*
        `lvh`, the full screen: iOS Safari's toolbar floats over the page, and a
        `dvh` panel stopped above it, leaving a black band under the toolbar.
        The overlay keeps to the visible `dvh` area so the toolbar never covers
        the copy or the scroll cue.

        On iOS Safari 26+ it is not sticky at all: it is pinned by a
        scroll-driven animation (`data-glass-pin`, see `GlassPins`), so Safari draws the
        photograph behind its status bar and tab bar instead of painting them
        flat. Everywhere else it is sticky, with the photograph's own foot as
        its background (`--hero-edge-bottom`, sampled live - see `sampleEdges`
        above) for older Safari, which tints its bars from it. It must be
        exactly the screen's height - taller, and WebKit lets a sticky panel
        scroll partly away, leaving the section showing through below it.
      */}
      <div
        ref={stickyRef}
        data-frame-stage
        data-glass-pin
        className="sticky top-0 h-[100lvh] w-full overflow-hidden bg-[var(--hero-edge-bottom)]"
      >
        <canvas
          ref={canvasRef}
          className="block h-full w-full"
          style={{
            opacity: isReady ? 1 : 0,
            transition: "opacity 700ms ease-out",
          }}
        />

        {children ? (
          <div
            data-hero-overlay
            className="pointer-events-none absolute inset-x-0 top-0 h-[100dvh]"
          >
            {children}
          </div>
        ) : null}
      </div>
    </div>
  );
}
